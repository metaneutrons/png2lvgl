#[instrument(skip(img, writer))]
fn write_indexed<W: Write>(
    img: &DynamicImage,
    writer: &mut W,
    var_name: &str,
    format_const: &str,
    bpp: u8,
    lvgl_version: LvglVersion,
) -> Result<()> {
    let gray = img.to_luma8();
    let (width, height) = gray.dimensions();
    let palette_size: usize = 1 << bpp;
    debug!(width, height, bpp, "Writing indexed data");

    write_array_open(writer, var_name)?;

    // Palette (RGBA32)
    for i in 0..palette_size {
        #[allow(clippy::cast_possible_truncation)]
        let val = (i * 255 / (palette_size - 1)) as u8;
        writeln!(
            writer,
            "  0x{val:02x}, 0x{val:02x}, 0x{val:02x}, 0xff, \t/*Color of index {i}*/"
        )?;
    }
    writeln!(writer)?;

    let data = pack_pixels_msb(width, height, bpp, |x, y| gray.get_pixel(x, y)[0]);

    write_data_array(writer, &data)?;
    writeln!(writer, "}};\n")?;

    let total_size = palette_size * PALETTE_ENTRY_SIZE + data.len();
    write_descriptor(
        writer,
        var_name,
        width,
        height,
        format_const,
        total_size,
        lvgl_version,
    )?;
    Ok(())
}

#[instrument(skip(img, writer))]
fn write_true_color<W: Write>(
    img: &DynamicImage,
    writer: &mut W,
    var_name: &str,
    alpha: bool,
    format_const: &str,
    big_endian: bool,
    lvgl_version: LvglVersion,
) -> Result<()> {
    let rgba = img.to_rgba8();
    let (width, height) = rgba.dimensions();
    debug!(width, height, alpha, big_endian, "Writing true color data");

    write_array_open(writer, var_name)?;

    let mut rgb_data = Vec::new();
    let mut alpha_data = Vec::new();

    for pixel in rgba.pixels() {
        let Rgba(channels) = *pixel;
        let rgb565 = encode_rgb565(channels[0], channels[1], channels[2]);

        #[allow(clippy::cast_possible_truncation)]
        let hi = (rgb565 >> 8) as u8;
        #[allow(clippy::cast_possible_truncation)]
        let lo = (rgb565 & 0xFF) as u8;

        if big_endian {
            rgb_data.push(hi);
            rgb_data.push(lo);
        } else {
            rgb_data.push(lo);
            rgb_data.push(hi);
        }

        if alpha {
            alpha_data.push(channels[3]);
        }
    }

    write_data_array(writer, &rgb_data)?;
    if alpha {
        writeln!(writer)?;
        write_data_array(writer, &alpha_data)?;
    }
    writeln!(writer, "}};\n")?;

    write_descriptor(
        writer,
        var_name,
        width,
        height,
        format_const,
        rgb_data.len() + alpha_data.len(),
        lvgl_version,
    )?;
    Ok(())
}

#[instrument(skip(img, writer))]
fn write_alpha<W: Write>(
    img: &DynamicImage,
    writer: &mut W,
    var_name: &str,
    format_const: &str,
    bpp: u8,
    lvgl_version: LvglVersion,
) -> Result<()> {
    let gray = img.to_luma8();
    let (width, height) = gray.dimensions();
    debug!(width, height, bpp, "Writing alpha data");

    write_array_open(writer, var_name)?;

    // No special case for 8 bpp any more. It existed only to route around the
    // overflowing mask above, and it hid the defect from the alpha formats
    // while the indexed ones ran into it.
    let data = pack_pixels_msb(width, height, bpp, |x, y| gray.get_pixel(x, y)[0]);

    write_data_array(writer, &data)?;
    writeln!(writer, "}};\n")?;

    write_descriptor(
        writer,
        var_name,
        width,
        height,
        format_const,
        data.len(),
        lvgl_version,
    )?;
    Ok(())
}

