/// Encode an RGB pixel to RGB565.
const fn encode_rgb565(red: u8, green: u8, blue: u8) -> u16 {
    ((red as u16 & RGB565_RED_MASK) << RGB565_RED_SHIFT)
        | ((green as u16 & RGB565_GREEN_MASK) << RGB565_GREEN_SHIFT)
        | (blue as u16 >> RGB565_BLUE_SHIFT)
}

fn write_array_open<W: Write>(writer: &mut W, var_name: &str) -> Result<()> {
    writeln!(
        writer,
        "const LV_ATTRIBUTE_MEM_ALIGN LV_ATTRIBUTE_LARGE_CONST \
         LV_ATTRIBUTE_IMG_{upper} uint8_t {var_name}_map[] = {{",
        upper = var_name.to_uppercase()
    )?;
    Ok(())
}

fn write_data_array<W: Write>(writer: &mut W, data: &[u8]) -> Result<()> {
    for (i, chunk) in data.chunks(HEX_BYTES_PER_LINE).enumerate() {
        if i > 0 {
            writeln!(writer)?;
        }
        write!(writer, "  ")?;
        for (j, byte) in chunk.iter().enumerate() {
            if j > 0 {
                write!(writer, ", ")?;
            }
            write!(writer, "0x{byte:02x}")?;
        }
        write!(writer, ",")?;
    }
    writeln!(writer)?;
    Ok(())
}

fn write_descriptor<W: Write>(
    writer: &mut W,
    var_name: &str,
    width: u32,
    height: u32,
    cf: &str,
    size: usize,
    lvgl_version: LvglVersion,
) -> Result<()> {
    writeln!(writer, "const lv_img_dsc_t {var_name} = {{")?;
    writeln!(writer, "  .header.cf = {cf},")?;

    if matches!(lvgl_version, LvglVersion::V8) {
        writeln!(writer, "  .header.always_zero = 0,")?;
        writeln!(writer, "  .header.reserved = 0,")?;
    }

    writeln!(writer, "  .header.w = {width},")?;
    writeln!(writer, "  .header.h = {height},")?;
    writeln!(writer, "  .data_size = {size},")?;
    writeln!(writer, "  .data = {var_name}_map,")?;
    writeln!(writer, "}};")?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use image::{DynamicImage, GrayImage, Luma, Rgb, RgbImage, Rgba, RgbaImage};

    use super::{ColorFormat, GenerateParams, LvglVersion, built_info, generate, pack_pixels_msb};

    fn solid_rgb(width: u32, height: u32, color: [u8; 3]) -> DynamicImage {
        let mut img = RgbImage::new(width, height);
        for pixel in img.pixels_mut() {
            *pixel = Rgb(color);
        }
        DynamicImage::ImageRgb8(img)
    }

    fn two_colors() -> DynamicImage {
        let img = RgbImage::from_fn(2, 1, |x, _| {
            if x == 0 {
                Rgb([0, 0, 0])
            } else {
                Rgb([255, 255, 255])
            }
        });
        DynamicImage::ImageRgb8(img)
    }

    fn render(
        img: &DynamicImage,
        format: &ColorFormat,
        version: LvglVersion,
        big_endian: bool,
    ) -> String {
        let mut out = Vec::new();
        let params = GenerateParams {
            var_name: "asset",
            format,
            lvgl_version: version,
            big_endian,
            source_file: "input.png",
            output_file: "output.c",
        };
        generate(img, &mut out, &params).expect("generate");
        String::from_utf8(out).expect("generated C must be valid UTF-8")
    }

    /// Up to and including v0.3.5 the header carried the git describe output,
    /// so a release build wrote a bare commit hash here and a tagged build the
    /// doubled `vv0.3.5`. It must be the package version, exactly once.
    #[test]
    fn header_states_the_package_version() {
        let text = render(
            &solid_rgb(1, 1, [0, 0, 0]),
            &ColorFormat::TrueColor,
            LvglVersion::V9,
            false,
        );
        let expected = format!("Generated by png2lvgl v{} ", built_info::PKG_VERSION);
        assert!(
            text.contains(&expected),
            "header does not carry the package version:\n{text}"
        );
        assert!(!text.contains("vv"), "version is prefixed twice:\n{text}");
    }

    #[test]
    fn header_names_the_target_and_the_format() {
        let v8 = render(
            &solid_rgb(1, 1, [0, 0, 0]),
            &ColorFormat::TrueColor,
            LvglVersion::V8,
            false,
        );
        assert!(v8.contains("Target: LVGL 8.x"), "{v8}");
        assert!(v8.contains("Format: RGB565 true color"), "{v8}");

        let v9 = render(
            &solid_rgb(1, 1, [0, 0, 0]),
            &ColorFormat::TrueColor,
            LvglVersion::V9,
            false,
        );
        assert!(v9.contains("Target: LVGL 9.x"), "{v9}");
    }

    /// The v8 descriptor carries two fields that v9 dropped. Emitting them into
    /// a v9 file breaks the build at the consumer.
    #[test]
    fn descriptor_matches_the_target_version() {
        let img = solid_rgb(2, 2, [255, 0, 0]);

        let v8 = render(&img, &ColorFormat::TrueColor, LvglVersion::V8, false);
        assert!(v8.contains("LV_IMG_CF_TRUE_COLOR"), "{v8}");
        assert!(v8.contains(".header.always_zero = 0,"), "{v8}");
        assert!(v8.contains(".header.reserved = 0,"), "{v8}");

        let v9 = render(&img, &ColorFormat::TrueColor, LvglVersion::V9, false);
        assert!(v9.contains("LV_COLOR_FORMAT_RGB565"), "{v9}");
        assert!(!v9.contains("always_zero"), "{v9}");
        assert!(!v9.contains(".header.reserved"), "{v9}");
    }

    #[test]
    fn descriptor_reports_the_image_dimensions() {
        let text = render(
            &solid_rgb(7, 3, [0, 0, 255]),
            &ColorFormat::TrueColor,
            LvglVersion::V9,
            false,
        );
        assert!(text.contains(".header.w = 7,"), "{text}");
        assert!(text.contains(".header.h = 3,"), "{text}");
    }

    #[test]
    fn variable_name_is_used_for_both_symbols() {
        let text = render(
            &solid_rgb(1, 1, [0, 0, 0]),
            &ColorFormat::TrueColor,
            LvglVersion::V9,
            false,
        );
        assert!(text.contains("const lv_img_dsc_t asset = {"), "{text}");
        assert!(text.contains("asset_map"), "{text}");
    }

    /// Pure red is 0xF800 in RGB565. The two byte orders must therefore differ,
    /// and the endianness must be recorded in the header.
    #[test]
    fn rgb565_byte_order_is_honoured() {
        let img = solid_rgb(1, 1, [255, 0, 0]);

        let little = render(&img, &ColorFormat::TrueColor, LvglVersion::V9, false);
        let big = render(&img, &ColorFormat::TrueColor, LvglVersion::V9, true);

        assert!(little.contains("little-endian"), "{little}");
        assert!(big.contains("big-endian"), "{big}");
        assert_ne!(little, big, "byte order had no effect on the output");
        assert!(
            little.contains("0x00, 0xf8"),
            "expected little-endian 0xF800:\n{little}"
        );
        assert!(
            big.contains("0xf8, 0x00"),
            "expected big-endian 0xF800:\n{big}"
        );
    }

    #[test]
    fn indexed_output_carries_a_palette() {
        let text = render(
            &two_colors(),
            &ColorFormat::Indexed1,
            LvglVersion::V9,
            false,
        );
        assert!(text.contains("LV_COLOR_FORMAT_I1"), "{text}");
        assert!(text.contains("1-bit indexed"), "{text}");
    }

    #[test]
    fn alpha_only_output_uses_the_alpha_constant() {
        let img = RgbaImage::from_fn(2, 2, |x, _| {
            Rgba([0, 0, 0, u8::try_from(x * 100).unwrap_or(0)])
        });
        let text = render(
            &DynamicImage::ImageRgba8(img),
            &ColorFormat::Alpha8,
            LvglVersion::V9,
            false,
        );
        assert!(text.contains("LV_COLOR_FORMAT_A8"), "{text}");
        assert!(text.contains("8-bit alpha"), "{text}");
    }

    /// Guards the C syntax at the coarsest level: unbalanced braces mean the
    /// consumer's build fails, and that is worth catching here rather than there.
    #[test]
    fn generated_c_has_balanced_braces() {
        for version in [LvglVersion::V8, LvglVersion::V9] {
            let text = render(
                &solid_rgb(3, 2, [1, 2, 3]),
                &ColorFormat::TrueColorAlpha,
                version,
                false,
            );
            let open = text.matches('{').count();
            let close = text.matches('}').count();
            assert_eq!(open, close, "unbalanced braces for {version:?}:\n{text}");
            assert!(
                text.trim_end().ends_with("};"),
                "file does not end with a declaration"
            );
        }
    }

    fn luma_row(values: &[u8]) -> DynamicImage {
        #[allow(clippy::cast_possible_truncation)]
        let width = values.len() as u32;
        DynamicImage::ImageLuma8(GrayImage::from_fn(width, 1, |x, _| {
            Luma([values[x as usize]])
        }))
    }

    /// `1u8 << 8` overflows. The mask therefore came out as 0 in a release
    /// build, so every 8 bpp pixel packed to zero, and a debug build panicked
    /// instead. Only the indexed path reached this: the alpha path used to
    /// route around it with a special case of its own.
    #[test]
    fn eight_bits_per_pixel_pass_through_unchanged() {
        let values = [50u8, 100, 150, 200];
        let packed = pack_pixels_msb(4, 1, 8, |x, _| values[x as usize]);
        assert_eq!(packed, values, "8 bpp must not alter the pixel");
    }

    /// The mask is now derived by shifting down. Guard that this still packs
    /// several pixels per byte for the sub-byte depths.
    #[test]
    fn four_bits_per_pixel_pack_two_to_a_byte() {
        let packed = pack_pixels_msb(2, 1, 4, |x, _| if x == 0 { 0xA0 } else { 0xB0 });
        assert_eq!(
            packed,
            [0xAB],
            "two 4 bpp pixels share one byte, high one first"
        );
    }

    /// Each row starts on a byte boundary, so a row that does not fill its last
    /// byte is flushed with the remaining bits left at zero.
    #[test]
    fn a_partial_row_is_flushed() {
        let packed = pack_pixels_msb(3, 1, 2, |_, _| 0xC0);
        assert_eq!(
            packed,
            [0b1111_1100],
            "three 2 bpp pixels fill six bits; the remaining two stay zero"
        );
    }

    /// The whole point, seen from outside: indexed8 used to emit an all-zero
    /// data array, which renders as a black image.
    #[test]
    fn indexed8_writes_the_pixel_values() {
        let text = render(
            &luma_row(&[50, 100, 150, 200]),
            &ColorFormat::Indexed8,
            LvglVersion::V9,
            false,
        );
        assert!(
            text.contains("0x32, 0x64, 0x96, 0xc8,"),
            "indexed8 lost the pixel values:\n{text}"
        );
    }
}
